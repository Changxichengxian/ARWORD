from math import sin, cos
from mathutils import Vector
from geometry import face_y

def meal(t):
    t = max(0.0, min(7.0, t))

    def track(keys):
        i = 0
        while i + 2 < len(keys) and t > keys[i + 1][0]:
            i += 1
        a, b = keys[i], keys[i + 1]
        dt = b[0] - a[0]
        u = max(0.0, min(1.0, (t - a[0]) / dt))

        def slope(k, j):
            if k == 0 or k == len(keys) - 1:
                return 0.0
            p, q, r = keys[k - 1], keys[k], keys[k + 1]
            incoming = (q[j] - p[j]) / (q[0] - p[0])
            outgoing = (r[j] - q[j]) / (r[0] - q[0])
            if incoming * outgoing <= 0.0:
                return 0.0
            return 2.0 * incoming * outgoing / (incoming + outgoing)

        return tuple(
            a[j] + (b[j] - a[j]) * u*u*(3.0 - 2.0*u)
            + dt*u*(1.0-u)*((1.0-u)*slope(i, j) - u*slope(i+1, j))
            for j in range(1, len(a))
        )

    left = Vector(track((
        (0, .083, -.176, .829), (.48, .076, -.185, .838),
        (1.03, .076, -.185, .838), (1.32, .079, -.187, .836),
        (1.69, .075, -.184, .840), (2.42, .074, -.183, .841),
        (3.25, .077, -.185, .837), (3.98, .077, -.185, .837),
        (4.40, .074, -.187, .844), (4.67, .076, -.188, .842),
        (5.12, .074, -.186, .843), (5.98, .076, -.185, .839),
        (6.60, .078, -.182, .836), (7, .078, -.182, .836)
    )))
    head = track((
        (0, .022, 0, .003), (.58, .185, -.022, .051),
        (1.28, .201, -.029, .060), (1.68, .149, -.016, .018),
        (2.01, .058, .018, -.026), (2.20, .045, .024, -.031),
        (2.44, .116, .011, -.017), (2.67, .121, .011, -.017),
        (2.98, .014, -.031, .003), (3.30, .053, -.041, .011),
        (3.54, .026, -.038, .013), (3.80, .065, -.015, .016),
        (3.98, .031, -.010, .020), (4.38, .156, -.009, .045),
        (4.66, .164, -.012, .044), (5.04, .067, .006, -.019),
        (5.37, .105, .014, -.022), (5.56, .107, .014, -.022),
        (5.87, .015, -.023, -.006), (6.13, .049, -.026, .003),
        (6.39, -.013, -.016, .005), (6.66, .037, -.007, .004),
        (7, .027, 0, .005)
    ))
    chest = track((
        (0, 0, 0, 0), (.83, .019, -.006, .009),
        (1.44, .022, -.006, .010), (2.02, .006, .007, -.008),
        (2.51, .026, .004, -.013), (3.13, -.005, -.005, 0),
        (4.41, .018, -.004, .008), (5.04, .006, .004, -.006),
        (5.49, .020, .004, -.009), (6.40, -.006, -.003, .002),
        (7, 0, 0, 0)
    ))

    hx, hy, hz = head
    lip_z = .952+(279-258)*.00323
    lip_y = face_y(0,lip_z)-.006
    y = lip_y*cos(hx) - (lip_z-.970)*sin(hx)
    z = lip_y*sin(hx) + (lip_z-.970)*cos(hx)
    x = z*sin(hy)
    outer_lip = Vector((x*cos(hz) - y*sin(hz),
                        x*sin(hz) + y*cos(hz) - .008,
                        .970 + z*cos(hy)))

    # Skim into the pile from the handle side; clear the rim before lifting.
    guide = left + Vector(track((
        (0, -.078, .012, .123), (.45, -.068, .012, .124),
        (.82, -.045, .017, .112), (1.07, -.017, .008, .090),
        (1.32, .034, -.003, .089), (1.50, .034, -.012, .106),
        (1.78, -.009, -.054, .155), (2.05, -.054, -.092, .193),
        (2.38, -.081, -.105, .209), (2.74, -.081, -.105, .209),
        (2.98, -.110, -.089, .173), (3.35, -.095, -.018, .133),
        (3.87, -.077, .008, .125), (4.18, -.060, .016, .119),
        (4.43, -.016, .008, .096), (4.63, .034, -.003, .089),
        (4.82, .012, -.033, .120), (5.03, -.046, -.088, .178),
        (5.34, -.076, -.104, .207), (5.63, -.076, -.104, .207),
        (5.90, -.102, -.084, .166), (6.24, -.083, -.013, .134),
        (6.72, -.070, .009, .120), (7, -.070, .009, .120)
    )))
    contact = track((
        (0, 0), (1.86, 0), (2.22, .72), (2.41, 1),
        (2.70, 1), (3.04, 0), (4.92, 0), (5.34, 1),
        (5.59, 1), (5.95, 0), (7, 0)
    ))[0]
    tip = guide * (1.0 - contact) + outer_lip * contact

    # Wrist to scoop: sweep sideways across the lip, with the handle
    # below the scoop and just camera-side of it throughout each bite.
    spoon = Vector(track((
        (0, .91, -.32, -.18), (.82, .89, -.37, -.24),
        (1.10, .84, -.38, -.40), (1.36, .92, -.35, -.14),
        (1.62, .95, -.14, .19), (1.91, .89, .018, .43),
        (2.13, .84, .022, .54), (2.48, .827, .008, .562),
        (2.72, .827, .008, .562), (3.20, .94, -.17, .24),
        (3.89, .91, -.34, -.12), (4.44, .88, -.36, -.32),
        (4.66, .95, -.25, -.11), (4.96, .91, .014, .40),
        (5.40, .835, .011, .550), (5.62, .835, .011, .550),
        (6.13, .94, -.18, .16), (6.70, .92, -.32, -.15),
        (7, .92, -.32, -.15)
    ))).normalized()

    # Limit the actual baked wrist, not the shorter solver input marker.
    shoulder = Vector((-.155, 0.0, .903))
    actual_length = .169642
    wrist = tip - actual_length * spoon
    arm = wrist - shoulder
    if arm.length > .305:
        wrist = shoulder + arm * (.305 / arm.length)
    right = wrist + (actual_length - .145) * spoon

    bite = track((
        (0, 0), (1.12, 0), (1.32, 1), (2.49, 1), (2.64, 0),
        (4.47, 0), (4.63, .72), (5.41, .72), (5.54, 0), (7, 0)
    ))[0]
    mouth = track((
        (0, .02), (.68, 0), (1.49, 0), (1.93, .16), (2.27, .92),
        (2.48, .96), (2.66, .09), (2.89, .02), (3.09, .23),
        (3.28, .03), (3.48, .17), (3.68, .01), (3.82, .08),
        (3.99, 0), (4.76, 0), (5.06, .38), (5.29, .75),
        (5.40, .78), (5.57, .05), (5.78, .02), (5.98, .18),
        (6.15, .02), (6.30, .10), (6.46, 0), (6.73, .03), (7, .02)
    ))[0]
    blink = track((
        (0, .03), (.44, .12), (.91, .05), (1.35, .18),
        (1.68, .02), (2.12, 0), (2.51, .28), (2.78, .90),
        (3.05, .83), (3.42, .32), (3.77, .24), (3.93, .87),
        (4.09, .07), (4.63, .16), (4.97, 0), (5.42, .23),
        (5.69, .79), (6.08, .46), (6.39, .91), (6.54, .78),
        (6.84, .09), (7, .04)
    ))[0]
    return dict(left=left, right=right, spoon=spoon, head=head, chest=chest,
                mouth=mouth, blink=blink, bite=bite)
